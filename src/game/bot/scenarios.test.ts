/**
 * Projection of a {@link BotSnapshot} into the stable, gameplay-meaningful
 * fields the golden snapshot pins. We deliberately avoid snapshotting every
 * field of `SimulationState` so incidental non-gameplay additions (e.g. a
 * new debug counter) do not churn the golden; only the numbers that drive
 * the GIF — mode, collisions, rewinds, orb angles, orbit height, obstacle
 * layout — are captured. Drift in any of *these* changes the visual and must
 * break the test.
 */
function project(snapshot: BotSnapshot) {
	const { state } = snapshot
	return {
		tick: snapshot.tick,
		mode: state.mode,
		capt: snapshot.capture,
		orbitY: Math.round(state.orbit.center.y),
		orb0: Math.round(state.orbit.orbs[0].angle * 1000) / 1000,
		orb1: Math.round(state.orbit.orbs[1].angle * 1000) / 1000,
		collisions: state.stats.collisions.total,
		rewinds: state.stats.rewinds,
		score: state.stats.score,
		obstacles: state.obstacles.length,
	}
}

function golden(scenario: BotScenario): readonly ReturnType<typeof project>[] {
	return runScenario(scenario).snapshots.map(project)
}

/**
 * Walk the snapshot sequence and return the tick at which a *new* collision
 * happened (collisions.total increments). Used to assert "a collision
 * occurred at tick T".
 */
function firstCollisionTick(scenario: BotScenario): number {
	let prev = 0
	for (const snap of runScenario(scenario).snapshots) {
		const total = snap.state.stats.collisions.total
		if (total > prev) {
			return snap.tick
		}
		prev = total
	}
	return Number.POSITIVE_INFINITY
}

